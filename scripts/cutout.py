"""
Cuts the students out of the hero banner and splits them into one layer per child.

    pip install "rembg[cpu]" pillow numpy
    npm run cutout

Reads public/hero/students-2000.webp (left untouched) and writes:
- public/hero/cutouts/students.webp      the whole group on a transparent background
- public/hero/cutouts/kid-<n>-<w>.webp    one cropped layer per child, 1000 and 2000 px wide canvases
- src/data/hero-cutouts.ts                where each layer sits on the canvas, in percent

Children are told apart by a seam that runs top to bottom between neighbouring heads, following the
strongest edges (jacket outlines) so the layers can move a little apart without visible cuts.
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter
from rembg import new_session, remove

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public/hero/students-2000.webp"
OUT = ROOT / "public/hero/cutouts"
MANIFEST = ROOT / "src/data/hero-cutouts.ts"
MODEL = "birefnet-portrait"
# Horizontal centre of every child's head on the 2000 px banner, left to right.
HEADS = [136, 336, 516, 706, 904, 1096, 1270, 1480, 1684, 1906]
WIDTHS = [1000, 2000]


def seam(cost: np.ndarray, lo: int, hi: int) -> np.ndarray:
    """Cheapest top-to-bottom path through cost[:, lo:hi]; returns its x for every row."""
    band = cost[:, lo:hi]
    h, w = band.shape
    acc = band.copy()
    back = np.zeros((h, w), dtype=np.int8)
    for y in range(1, h):
        prev = acc[y - 1]
        options = np.stack([np.r_[np.inf, np.inf, prev[:-2]], np.r_[np.inf, prev[:-1]], prev, np.r_[prev[1:], np.inf], np.r_[prev[2:], np.inf, np.inf]])
        pick = options.argmin(axis=0)
        acc[y] += options[pick, np.arange(w)]
        back[y] = pick - 2
    xs = np.zeros(h, dtype=int)
    xs[-1] = int(acc[-1].argmin())
    for y in range(h - 1, 0, -1):
        xs[y - 1] = xs[y] + back[y, xs[y]]
    return xs + lo


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    banner = Image.open(SRC).convert("RGB")
    group = remove(banner, session=new_session(MODEL))
    group.save(OUT / "students.webp", quality=85, method=6)

    rgba = np.asarray(group)
    alpha = rgba[..., 3].astype(np.float32) / 255
    gray = banner.convert("L").filter(ImageFilter.GaussianBlur(1.5))
    edges = np.asarray(gray.filter(ImageFilter.FIND_EDGES), dtype=np.float32) / 255
    # Free to cut through background, cheap along edges, expensive through flat cloth and faces.
    cost = alpha * (1.0 - np.clip(edges * 4, 0, 0.95)) + 0.002

    h, w = alpha.shape
    owner = np.zeros((h, w), dtype=np.int8)
    cols = np.arange(w)[None, :]
    for i in range(len(HEADS) - 1):
        gap = HEADS[i + 1] - HEADS[i]
        xs = seam(cost, HEADS[i] + gap // 5, HEADS[i + 1] - gap // 5)
        owner[cols > xs[:, None]] = i + 1

    layers = []
    for i in range(len(HEADS)):
        mask = (owner == i) & (rgba[..., 3] > 0)
        ys, xs = np.nonzero(mask)
        x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
        layer = rgba.copy()
        layer[..., 3] = np.where(mask, rgba[..., 3], 0)
        crop = Image.fromarray(layer[y0:y1, x0:x1])
        for target in WIDTHS:
            k = target / w
            size = (max(1, round((x1 - x0) * k)), max(1, round((y1 - y0) * k)))
            crop.resize(size, Image.LANCZOS).save(OUT / f"kid-{i + 1}-{target}.webp", quality=82, method=6)
        layers.append(
            {
                "x": round(x0 / w * 100, 3),
                "y": round(y0 / h * 100, 3),
                "w": round((x1 - x0) / w * 100, 3),
                "h": round((y1 - y0) / h * 100, 3),
            }
        )

    data = json.dumps({"width": w, "height": h, "sizes": WIDTHS, "kids": layers})
    MANIFEST.write_text(f"// Generated by `npm run cutout` (scripts/cutout.py). Do not edit by hand.\n\nexport const HERO_CUTOUTS = {data} as const\n")
    print(f"{len(layers)} layers written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
